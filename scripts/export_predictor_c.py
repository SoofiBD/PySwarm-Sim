"""Export the tiny predictor as an int8 C header (symmetric per-tensor scales)."""
import argparse
from pathlib import Path

import numpy as np

from app.comm.predictor import DEFAULT_WEIGHTS, OUT_SCALE


def quantize(w: np.ndarray) -> tuple[np.ndarray, float]:
    """w ~= q * scale, q in [-127, 127]."""
    peak = float(np.abs(w).max()) if w.size else 0.0
    scale = peak / 127.0 if peak > 0 else 1.0
    return np.clip(np.round(w / scale), -127, 127).astype(np.int8), scale


def export(weights: Path, out: Path) -> None:
    with np.load(weights) as z:
        tensors = {k: z[k] for k in ("w1", "b1", "w2", "b2")}
    n_in, n_hidden = tensors["w1"].shape
    n_out = tensors["w2"].shape[1]
    lines = [
        "/* Tiny MLP peer-position predictor: in -> hidden (tanh) -> out.",
        " * Real value = q * scale. Output is a position residual in units of",
        " * PREDICTOR_OUT_SCALE metres, added to the constant-velocity guess.",
        " * Inputs are features() in app/comm/predictor.py. Weights are row-major [in][out].",
        " * Generated by scripts/export_predictor_c.py. */",
        "#ifndef PREDICTOR_WEIGHTS_H",
        "#define PREDICTOR_WEIGHTS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define PREDICTOR_N_IN {n_in}",
        f"#define PREDICTOR_N_HIDDEN {n_hidden}",
        f"#define PREDICTOR_N_OUT {n_out}",
        f"#define PREDICTOR_OUT_SCALE {OUT_SCALE:.1f}f",
        "",
    ]
    dims = {"w1": "PREDICTOR_N_IN * PREDICTOR_N_HIDDEN", "b1": "PREDICTOR_N_HIDDEN",
            "w2": "PREDICTOR_N_HIDDEN * PREDICTOR_N_OUT", "b2": "PREDICTOR_N_OUT"}
    for name, w in tensors.items():
        q, scale = quantize(w)
        shape = " * ".join(str(d) for d in w.shape)
        lines.append(f"/* {dims[name]} */")
        lines.append(f"static const int8_t predictor_{name}[{shape}] = {{")
        flat = q.ravel().tolist()
        for i in range(0, len(flat), 16):
            lines.append("    " + ", ".join(str(v) for v in flat[i:i + 16]) + ",")
        lines.append("};")
        lines.append(f"static const float predictor_{name}_scale = {scale:.9g}f;")
        lines.append("")
    lines.append("#endif /* PREDICTOR_WEIGHTS_H */")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--weights", type=Path, default=DEFAULT_WEIGHTS)
    ap.add_argument("--out", type=Path, default=Path("build/predictor_weights.h"))
    args = ap.parse_args()
    export(args.weights, args.out)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
